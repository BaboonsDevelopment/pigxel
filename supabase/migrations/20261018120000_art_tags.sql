-- The old rule allowed only the five categories, at most five of them.
do $$
declare
  rule text;
begin
  for rule in
    select conname from pg_constraint
    where conrelid = 'public.tiles'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%tags%'
  loop
    execute format('alter table public.tiles drop constraint %I', rule);
  end loop;
end
$$;

-- Existing tags become their lowercase tag ("Buildings" → buildings); any
-- without one are dropped. Only tags change, so updated_at stays put.
update public.tiles t
set tags = coalesce(
  (
    select array_agg(distinct lower(old_tag))
    from unnest(t.tags) as old_tag
    where lower(old_tag) in (select id from public.art_tags)
  ),
  '{}'
)
where cardinality(t.tags) > 0;

alter table public.tiles
  add constraint tiles_tags_check check (cardinality(tags) <= 10);

create function private.check_art_tags()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if exists (
    select 1 from unnest(new.tags) as tag
    where not exists (select 1 from public.art_tags a where a.id = tag)
  ) then
    raise exception 'Unknown tag' using errcode = '23514';
  end if;
  return new;
end;
$$;

revoke all on function private.check_art_tags() from public, anon, authenticated;

create trigger tiles_check_art_tags
  before insert or update of tags on public.tiles
  for each row execute function private.check_art_tags();
