export const ART_TAGS: readonly string[] = Object.values(ART_TAG_GROUPS).flat();

const ART_TAG_SET: ReadonlySet<string> = new Set(ART_TAGS);

export const isArtTag = (tag: unknown): tag is string =>
  typeof tag === "string" && ART_TAG_SET.has(tag);

/** Most tags one art can have; the database checks it too. */
export const MAX_ART_TAGS = 10;

/**
 * Tags matching what someone typed: those starting with it first, then those
 * containing it, shortest first within each (so "sci" offers sci-fi before
 * scientist), leaving out ones already chosen.
 */
export function matchArtTags(
  typed: string,
  chosen: readonly string[] = [],
  limit = 8,
): string[] {
  const term = typed
    .trim()
    .replace(/^#/, "")
    .toLowerCase()
    .replace(/\s+/g, "-");
  if (!term) return [];
  const free = ART_TAGS.filter((tag) => !chosen.includes(tag));
  const starts = free.filter((tag) => tag.startsWith(term));
  const contains = free.filter(
    (tag) => !tag.startsWith(term) && tag.includes(term),
  );
  const byLength = (a: string, b: string) =>
    a.length - b.length || a.localeCompare(b);
  return [...starts.sort(byLength), ...contains.sort(byLength)].slice(0, limit);
}
